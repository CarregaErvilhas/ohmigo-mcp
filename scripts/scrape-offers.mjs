// Fetches the newest price post from custofinal.blogspot.com and writes
// offers/custofinal.json. Run by .github/workflows/offers.yml (weekly, or by
// hand), which opens a pull request when the file changes, so a person looks
// at every price change before it reaches users.
//
//   npm run offers:scrape            write offers/custofinal.json
//   npm run offers:scrape -- --check parse only, write nothing
//
// The author publishes a NEW post for each update (not an edit of the old
// one), so we can't use a fixed URL. Blogger serves every blog's posts as a
// JSON feed; we take the newest post that contains the price table.
//
// Exit codes: 0 ok; 1 nothing usable (feed down, no table, layout changed);
// 3 ok but some "Postos" labels aren't in offers/networks.json (the PR says
// which, and those rows are left out until someone maps them).

import { readFileSync, writeFileSync } from 'node:fs';
import { parseTables, toOffers } from '../src/offers-parse.js';

const FEED = 'https://custofinal.blogspot.com/feeds/posts/default?alt=json&max-results=25';
const OUT = new URL('../offers/custofinal.json', import.meta.url);
const NETWORKS = new URL('../offers/networks.json', import.meta.url);
const check = process.argv.includes('--check');

const res = await fetch(FEED, { headers: { 'user-agent': 'ohmigo-offers-scraper (+https://github.com/CarregaErvilhas)' }, signal: AbortSignal.timeout(30_000) });
if (!res.ok) { console.error(`feed: HTTP ${res.status}`); process.exit(1); }
const entries = (await res.json()).feed?.entry || [];
const post = entries
  .filter(e => /class="[^"]*evtable/.test(e.content?.$t || ''))
  .sort((a, b) => b.updated.$t.localeCompare(a.updated.$t))[0];
if (!post) { console.error('no post with a price table in the feed'); process.exit(1); }

const url = post.link.find(l => l.rel === 'alternate')?.href;
const updated = post.updated.$t;
const tables = parseTables(post.content.$t);
const networks = JSON.parse(readFileSync(NETWORKS, 'utf8')).networks;
const { offers, unmapped, skipped } = toOffers(tables, networks, { url, checkedAt: updated.slice(0, 10), origin: 'custofinal' });
if (!offers.length) { console.error('parsed the tables but got no offers'); process.exit(1); }

const out = {
  about: 'Generated by scripts/scrape-offers.mjs from the newest price post of custofinal.blogspot.com ("Preços (finais) kWh Portugal": final prices with VAT). Do not edit by hand: corrections go in offers/manual.json, which wins over this file.',
  source: { name: 'Preços (finais) kWh Portugal', author: 'Alexandre Moleiro', blog: 'https://custofinal.blogspot.com', post: url, published: post.published.$t, updated },
  offers: offers.sort((a, b) => a.id.localeCompare(b.id)),
  unmapped,
  skipped,
};

console.log(`${url} (updated ${updated}): ${tables.map(t => `${t.kind} ${t.rows.length} rows`).join(', ')} -> ${offers.length} offers`);
if (skipped.length) console.log(`left out (chargers unknown): ${skipped.join('; ')}`);
if (unmapped.length) console.log(`UNMAPPED networks, add them to offers/networks.json: ${unmapped.join(', ')}`);

if (!check) {
  // No timestamp of our own in the file: it only changes when the blog does,
  // so the weekly job opens a PR only when there's something to review.
  writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
  console.log(`wrote ${OUT.pathname}`);
}
process.exit(unmapped.length ? 3 : 0);
