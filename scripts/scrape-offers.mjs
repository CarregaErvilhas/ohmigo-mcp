// Fetches the newest price post from custofinal.blogspot.com and writes
// offers/custofinal.json. Run by .github/workflows/offers.yml (weekly, or by
// hand), which opens a pull request when the file changes, so a person looks
// at every price change before it reaches users.
//
//   npm run offers:scrape            write offers/custofinal.json
//   npm run offers:scrape -- --check parse only, write nothing
//
// The author publishes a NEW post for each update (not an edit of the old
// one), so we can't use a fixed URL. Blogger serves every blog's posts as a
// JSON feed; we take the most recently published price list, and lay over it
// any notice about one provider published since (an edit to an old post
// doesn't count, see pricePosts() and applyNotices()). Offers from a notice
// get the notice as their source.
//
// Exit codes: 0 ok; 1 nothing usable (feed down, no table, layout changed);
// 3 ok but some "Postos" labels aren't in offers/networks.json (the PR says
// which, and those rows are left out until someone maps them).

import { readFileSync, writeFileSync } from 'node:fs';
import { applyNotices, parseTables, pricePosts, toOffers } from '../src/offers-parse.js';

const FEED = 'https://custofinal.blogspot.com/feeds/posts/default?alt=json&max-results=25';
const OUT = new URL('../offers/custofinal.json', import.meta.url);
const NETWORKS = new URL('../offers/networks.json', import.meta.url);
const check = process.argv.includes('--check');

const res = await fetch(FEED, { headers: { 'user-agent': 'ohmigo-offers-scraper (+https://github.com/CarregaErvilhas)' }, signal: AbortSignal.timeout(30_000) });
if (!res.ok) { console.error(`feed: HTTP ${res.status}`); process.exit(1); }
const { list, notices } = pricePosts((await res.json()).feed?.entry || []);
if (!list) { console.error('no price list in the feed'); process.exit(1); }

const read = (post, notice) => ({
  post,
  tables: parseTables(post.content.$t, { notice }),
  source: { url: post.link.find(l => l.rel === 'alternate')?.href, checkedAt: post.updated.$t.slice(0, 10), origin: 'custofinal' },
});
const { posts, replaced } = applyNotices([read(list, false), ...notices.map(n => read(n, true))]);
const networks = JSON.parse(readFileSync(NETWORKS, 'utf8')).networks;
const offers = [], unmapped = new Set(), skipped = [];
for (const p of posts) {
  const r = toOffers(p.tables, networks, p.source);
  offers.push(...r.offers);
  r.unmapped.forEach(u => unmapped.add(u));
  skipped.push(...r.skipped);
}
const dup = offers.map(o => o.id).find((id, i, all) => all.indexOf(id) !== i);
if (dup) { console.error(`two offers with id ${dup}`); process.exit(1); }
if (!offers.length) { console.error('parsed the tables but got no offers'); process.exit(1); }

const url = posts[0].source.url;
const updated = list.updated.$t;
const tables = posts.flatMap(p => p.tables);
const out = {
  about: 'Generated by scripts/scrape-offers.mjs from the newest price list of custofinal.blogspot.com, with the notices published since laid over it ("Preços (finais) kWh Portugal": final prices with VAT). Do not edit by hand: corrections go in offers/manual.json, which wins over this file.',
  source: {
    name: 'Preços (finais) kWh Portugal', author: 'Alexandre Moleiro', blog: 'https://custofinal.blogspot.com', post: url, published: list.published.$t, updated,
    ...(replaced.length && { notices: replaced.map(r => ({ post: r.url, published: posts.find(p => p.source.url === r.url).post.published.$t, replaces: r.labels })) }),
  },
  offers: offers.sort((a, b) => a.id.localeCompare(b.id)),
  unmapped: [...unmapped],
  skipped,
};

console.log(`${url} (updated ${updated}): ${tables.map(t => `${t.kind} ${t.rows.length} rows`).join(', ')} -> ${offers.length} offers`);
for (const r of replaced) console.log(`NOTICE ${r.url} replaces the pay-as-you-go rows of: ${r.labels.join(', ')}`);
const perMinute = offers.filter(o => o.perMinute);
if (perMinute.length) console.log(`billed per minute too (no rate, left out of the prices): ${perMinute.map(o => `${o.id} ${o.perMinute.join('/')}`).join('; ')}`);
if (skipped.length) console.log(`left out (chargers unknown): ${skipped.join('; ')}`);
if (unmapped.size) console.log(`UNMAPPED networks, add them to offers/networks.json: ${[...unmapped].join(', ')}`);

if (!check) {
  // No timestamp of our own in the file: it only changes when the blog does,
  // so the weekly job opens a PR only when there's something to review.
  writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
  console.log(`wrote ${OUT.pathname}`);
}
process.exit(unmapped.size ? 3 : 0);
